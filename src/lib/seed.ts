export function seedSearch(query: string): TitleSummary[] {
  const needle = query.trim().toLowerCase();
  if (!needle) return [];

  return seedTitles
    .filter(
      (title) =>
        title.name.toLowerCase().includes(needle) ||
        title.genres.some((genre) => genre.toLowerCase().includes(needle)),
    )
    .sort(
      (a, b) =>
        Number(b.name.toLowerCase().startsWith(needle)) -
          Number(a.name.toLowerCase().startsWith(needle)) || a.name.localeCompare(b.name),
    )
    .slice(0, 20)
    .map(({ key, tmdbId, type, name, year, posterPath, overview }) => ({
      key,
      tmdbId,
      type,
      name,
      year,
      posterPath,
      overview,
    }));
}

export function seedTitleByKey(key: string): Title | null {
  return seedTitles.find((title) => title.key === key) ?? null;
}
