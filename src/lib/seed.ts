function makeTitle(
  key: string,
  tmdbId: number,
  imdbId: string,
  type: "movie" | "tv",
  name: string,
  year: string,
  genres: string[],
  directors: string[],
  cast: string[],
  runtimeMinutes: number,
  seasons: SeasonInfo[] = [],
): Title {
  return {
    key,
    tmdbId,
    imdbId,
    type,
    name,
    year,
    posterPath: SEED_POSTERS[key] ?? null,
    overview: "",
    genres,
    directors,
    cast,
    runtimeMinutes,
    seasons,
    critic: null,
    addedAt: new Date(0).toISOString(),
  };
}

function season(
  seasonNumber: number,
  episodeCount: number,
  year: string,
  name = `Season ${seasonNumber}`,
): SeasonInfo {
  return { seasonNumber, name, episodeCount, year };
}

